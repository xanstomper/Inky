"""tmux-backed persistent sessions.

Every Inky tab is a tmux session on a private socket. VTE attaches as a
client, so closing a window, detaching a tab or crashing the UI never kills
the shell or the AI agent running inside it.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import uuid
from pathlib import Path

from .config import SOCKET, TMUX_CONF

CONF = """# Generated by Inky — safe to delete, it is rewritten on launch.
set -g default-terminal "tmux-256color"
set -g terminal-overrides ",*:RGB"
set -g status off
set -g mouse on
set -g history-limit 100000
set -g escape-time 10
set -g focus-events on
set -g set-clipboard on
set -g destroy-unattached off
set -g exit-empty on
set -g renumber-windows on
set -g base-index 0
set -g pane-base-index 0
set -g visual-activity off
set -g visual-bell off
set -g monitor-activity off
set -g mode-keys vi
setw -g aggressive-resize on
bind -T copy-mode-vi MouseDragEnd1Pane send-keys -X copy-pipe-and-cancel "xclip -selection clipboard -i"
"""

FIELD_SEP = "\t"


class TmuxError(RuntimeError):
    pass


def available() -> bool:
    return shutil.which("tmux") is not None


class Tmux:
    def __init__(self, socket: str = SOCKET, conf_path: Path = TMUX_CONF) -> None:
        self.socket = socket
        self.conf_path = Path(conf_path)
        self._base = ["tmux", "-L", socket]

    # -- plumbing ------------------------------------------------------
    def _run(self, *args: str, input_text: str | None = None, timeout: float = 6.0) -> str:
        if not available():
            raise TmuxError("tmux is not installed")
        try:
            proc = subprocess.run(
                self._base + [str(a) for a in args],
                input=input_text,
                capture_output=True,
                text=True,
                timeout=timeout,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise TmuxError(str(exc)) from exc
        if proc.returncode != 0:
            raise TmuxError(proc.stderr.strip() or f"tmux {' '.join(args)} failed")
        return proc.stdout

    def ensure_server(self) -> None:
        self.conf_path.parent.mkdir(parents=True, exist_ok=True)
        current = ""
        try:
            current = self.conf_path.read_text(encoding="utf-8")
        except OSError:
            pass
        if current != CONF:
            try:
                self.conf_path.write_text(CONF, encoding="utf-8")
            except OSError:
                pass
        # A server with no sessions exits immediately (exit-empty), so only
        # touch a live one. Otherwise the config is applied by the first
        # new-session via `-f` below.
        try:
            self._run("list-sessions")
        except TmuxError:
            return
        try:
            self._run("source-file", str(self.conf_path))
        except TmuxError:
            pass

    # -- sessions ------------------------------------------------------
    @staticmethod
    def new_id() -> str:
        return f"inky-{uuid.uuid4().hex[:8]}"

    def new_session(self, name: str, cwd: str | None = None,
                    command: str | None = None) -> str:
        args = ["-f", str(self.conf_path), "new-session", "-d", "-s", name,
                "-x", "120", "-y", "36"]
        if cwd and os.path.isdir(cwd):
            args += ["-c", cwd]
        if command:
            args.append(command)
        self._run(*args)
        return name

    def has_session(self, name: str) -> bool:
        try:
            self._run("has-session", "-t", f"={name}")
            return True
        except TmuxError:
            return False

    def kill_session(self, name: str) -> None:
        try:
            self._run("kill-session", "-t", f"={name}")
        except TmuxError:
            pass

    def attach_argv(self, name: str) -> list[str]:
        return [*self._base, "attach-session", "-t", f"={name}"]

    def sessions(self) -> list[dict]:
        try:
            out = self._run(
                "list-sessions", "-F",
                FIELD_SEP.join([
                    "#{session_name}", "#{session_attached}",
                    "#{session_created}", "#{session_windows}",
                ]),
            )
        except TmuxError:
            return []
        rows = []
        for line in out.splitlines():
            parts = line.split(FIELD_SEP)
            if len(parts) < 4:
                continue
            rows.append({
                "name": parts[0],
                "attached": parts[1] not in ("0", ""),
                "created": int(parts[2] or 0),
                "windows": int(parts[3] or 1),
            })
        return rows

    def panes(self) -> dict[str, dict]:
        """One call for every pane on the socket, keyed by session name."""
        try:
            out = self._run(
                "list-panes", "-a", "-F",
                FIELD_SEP.join([
                    "#{session_name}", "#{pane_pid}", "#{pane_current_command}",
                    "#{pane_current_path}", "#{pane_title}", "#{pane_in_mode}",
                    "#{pane_width}", "#{pane_height}",
                ]),
            )
        except TmuxError:
            return {}
        result: dict[str, dict] = {}
        for line in out.splitlines():
            parts = line.split(FIELD_SEP)
            if len(parts) < 6:
                continue
            result[parts[0]] = {
                "pid": int(parts[1]) if parts[1].isdigit() else 0,
                "command": parts[2],
                "path": parts[3],
                "title": parts[4],
                "in_mode": parts[5] == "1",
                "width": int(parts[6]) if parts[6].isdigit() else 0,
                "height": int(parts[7]) if parts[7].isdigit() else 0,
            }
        return result

    def capture(self, name: str, history: int = 50000) -> str:
        try:
            return self._run(
                "capture-pane", "-p", "-J", "-t", f"={name}:", "-S", f"-{int(history)}"
            )
        except TmuxError:
            return ""

    def capture_screen(self, name: str) -> str:
        try:
            return self._run("capture-pane", "-p", "-t", f"={name}:")
        except TmuxError:
            return ""

    # -- input ---------------------------------------------------------
    def send_text(self, name: str, text: str, submit: bool = False) -> None:
        """Paste text as a bracketed paste, optionally pressing Enter.

        Bracketed paste keeps multi-line AI prompts intact instead of
        executing every line as a shell command.
        """
        if not text:
            return
        buffer_name = f"inky-{os.getpid()}-{uuid.uuid4().hex[:6]}"
        # paste-buffer and send-keys need a *pane* target; `=name:` pins the
        # session and lets tmux pick its current window/pane.
        target = f"={name}:"
        try:
            self._run("load-buffer", "-b", buffer_name, "-", input_text=text)
            self._run("paste-buffer", "-p", "-d", "-b", buffer_name, "-t", target)
            if submit:
                self._run("send-keys", "-t", target, "Enter")
        except TmuxError:
            pass


