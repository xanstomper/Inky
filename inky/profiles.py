"""Named launch profiles: font, palette and startup command in one file.

GNOME Terminal keeps profiles in dconf, where they are invisible and not
portable. An Inky profile is a plain JSON file in ``~/.config/inky/profiles``,
so it can be committed, copied to another machine, or generated by a script —
and a tab opened with a profile remembers it.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

from .config import PROFILES_DIR
from .util import slugify

FONT_KEYS = ("family", "size", "line_height", "weight")


def _clean_font(raw) -> dict:
    """Keep only font keys with plausible values, clamped to the UI's range."""
    font: dict = {}
    if not isinstance(raw, dict):
        return font
    family = raw.get("family")
    if isinstance(family, str) and family.strip():
        font["family"] = family.strip()
    try:
        if raw.get("size"):
            font["size"] = max(6.0, min(28.0, float(raw["size"])))
    except (TypeError, ValueError):
        pass
    try:
        if raw.get("line_height"):
            font["line_height"] = max(0.8, min(2.0, float(raw["line_height"])))
    except (TypeError, ValueError):
        pass
    try:
        if raw.get("weight"):
            font["weight"] = max(100, min(900, int(raw["weight"])))
    except (TypeError, ValueError):
        pass
    return font


@dataclass
class Profile:
    """One launch bundle. Every field is optional except ``name``."""

    slug: str
    name: str
    theme: str = ""
    font: dict = field(default_factory=dict)
    command: str = ""
    cwd: str = ""
    description: str = ""

    @classmethod
    def from_dict(cls, slug: str, data) -> "Profile":
        data = data if isinstance(data, dict) else {}
        name = str(data.get("name") or slug.replace("-", " ").title())[:48]
        return cls(
            slug=slug,
            name=name,
            theme=str(data.get("theme") or ""),
            font=_clean_font(data.get("font")),
            command=str(data.get("command") or ""),
            cwd=str(data.get("cwd") or ""),
            description=str(data.get("description") or ""),
        )

    def to_dict(self) -> dict:
        data: dict = {"name": self.name}
        for key in ("theme", "command", "cwd", "description"):
            value = getattr(self, key)
            if value:
                data[key] = value
        if self.font:
            data["font"] = dict(self.font)
        return data

    # -- use ------------------------------------------------------------
    def font_for(self, base: dict) -> dict:
        """The window font with this profile's overrides applied."""
        merged = dict(base or {})
        merged.update({k: v for k, v in self.font.items() if k in FONT_KEYS})
        return merged

    def start_cwd(self, fallback: str) -> str:
        if not self.cwd:
            return fallback
        path = Path(self.cwd).expanduser()
        return str(path) if path.is_dir() else fallback

    def summary(self) -> str:
        bits = [self.theme or "window theme"]
        if self.command:
            bits.append(self.command)
        if self.cwd:
            bits.append(self.cwd)
        return " · ".join(bits)


# -- storage -----------------------------------------------------------
def profile_path(slug: str) -> Path:
    return Path(PROFILES_DIR) / f"{slug}.json"


def is_user_profile(slug: str) -> bool:
    return bool(slug) and profile_path(slug).is_file()


def load_profiles() -> dict[str, Profile]:
    """Every profile on disk, sorted by display name. Broken files are skipped."""
    profiles: dict[str, Profile] = {}
    directory = Path(PROFILES_DIR)
    if not directory.is_dir():
        return profiles
    for path in sorted(directory.glob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            if not isinstance(data, dict):
                continue
            profile = Profile.from_dict(path.stem, data)
        except (OSError, json.JSONDecodeError, ValueError):
            continue
        profiles[profile.slug] = profile
    return dict(sorted(profiles.items(), key=lambda item: item[1].name.lower()))


def save_profile(profile: Profile) -> Path:
    path = profile_path(profile.slug)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(profile.to_dict(), indent=2) + "\n", encoding="utf-8")
    return path


def delete_profile(slug: str) -> bool:
    path = profile_path(slug)
    if not path.is_file():
        return False
    path.unlink()
    return True


def slug_for(name: str, existing: dict | None = None) -> str:
    """A filesystem-safe slug, suffixed until it does not collide."""
    base = slugify((name or "").lower()).strip("-._")[:36] or "profile"
    taken = set(existing or {})
    if base not in taken and not is_user_profile(base):
        return base
    for index in range(2, 100):
        candidate = f"{base}-{index}"
        if candidate not in taken and not is_user_profile(candidate):
            return candidate
    return f"{base}-{len(taken) + 2}"


def from_tab(name: str, font: dict, theme_slug: str, cwd: str, command: str,
             existing: dict | None = None, description: str = "") -> Profile:
    """Snapshot the tab you are looking at into a reusable profile."""
    return Profile(
        slug=slug_for(name, existing),
        name=(name or "").strip()[:48] or "Profile",
        theme=theme_slug or "",
        font={k: v for k, v in (font or {}).items() if k in FONT_KEYS},
        command=command or "",
        cwd=cwd or "",
        description=description,
    )
